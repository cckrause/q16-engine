void sin_cos_fixed(Angle14 angle, Fixed16 *sin_out, Fixed16 *cos_out) {
  angle &= ANGLE14_MASK;

  // Quadrant: 0=[0,90), 1=[90,180), 2=[180,270), 3=[270,360)
  int32_t quadrant = (angle >> 12) & 3;
  int32_t index = angle & 0xFFF;

  Fixed16 cos_val;
  Fixed16 sin_val;

  switch (quadrant) {
  case 0:
    cos_val = g_cos_table[index];
    sin_val = g_cos_table[4095 - index];
    break;
  case 1:
    cos_val = -g_cos_table[4095 - index];
    sin_val = g_cos_table[index];
    break;
  case 2:
    cos_val = -g_cos_table[index];
    sin_val = -g_cos_table[4095 - index];
    break;
  case 3:
    cos_val = g_cos_table[4095 - index];
    sin_val = -g_cos_table[index];
    break;
  default:
    cos_val = 0;
    sin_val = 0;
    break;
  }

  *sin_out = sin_val;
  *cos_out = cos_val;
}
